#!/usr/bin/env node
// Lists where each control of the kit's state atlas is drawn, so compare.mjs can find it in the atlas image.
// It opens kit/components/atlas.html with the kit's own verifier (headless Chromium), reads the rectangle of every
// cell, control and named part, and writes atlas-cells.json plus (with --png) the rendering it measured.
// It reads the kit and changes nothing in it. Needs the kit's dependencies: cd kit && pnpm install --frozen-lockfile
//
// Usage: node atlas-cells.mjs [--out atlas-cells.json] [--png FILE]
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { VIEWPORT, openAtlas } from '../../kit/verify/atlas.mjs';

const args = process.argv.slice(2), value = name => { const i = args.indexOf(name); return i < 0 ? null : args[i + 1]; };
const out = value('--out') ?? fileURLToPath(new URL('./atlas-cells.json', import.meta.url));
const { page, close } = await openAtlas();
try {
  const cells = await page.evaluate(() => {
    const rect = el => { const r = el.getBoundingClientRect(); return { x: r.left, y: r.top, w: r.width, h: r.height }; };
    const slug = text => text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
    const kind = el => el.matches('[data-gui95-spin]') ? 'updown' : el.getAttribute('role') ?? (el.tagName === 'INPUT' ? el.type : el.className && typeof el.className === 'string' && el.className.split(' ')[0] !== 'atlas-label' && el.tagName === 'DIV' ? el.className.split(' ')[0] : el.tagName.toLowerCase());
    const result = {};
    for (const cell of document.querySelectorAll('#atlas > .cell')) {
      const control = cell.firstElementChild;
      const label = control.getAttribute('aria-label') ?? control.querySelector('[aria-label]')?.getAttribute('aria-label') ?? '';
      let key = cell.id ? cell.id.replace(/-cell$/, '') : slug(`${kind(control)} ${label}`);
      while (result[key]) key += '-2';
      result[key] = { ...rect(control), cell: rect(cell), what: `${kind(control)}${label ? ` "${label}"` : ''}` };
      const counts = {};
      for (const part of control.querySelectorAll('button, input, [role=option], [role=tab], [role=tabpanel], [role=separator], [role=treeitem] > [data-gui95-tree-label], .title-bar, .window-body, .status-bar > div, legend')) {
        const name = kind(part), n = counts[name] = (counts[name] ?? -1) + 1;
        const partLabel = part.getAttribute('aria-label');
        result[`${key}.${name}${n}`] = { ...rect(part), partOf: key, what: `${name}${partLabel ? ` "${partLabel}"` : ''}${part.matches('[data-gui95-state=pressed]') ? ' pressed' : ''}${part.matches(':disabled,[aria-disabled=true]') ? ' unavailable' : ''}${part.matches(':focus') ? ' highlighted' : ''}${part.matches('[aria-checked=true],[aria-selected=true]') ? ' checked or selected' : ''}` };
      }
    }
    return result;
  });
  const fractional = Object.entries(cells).filter(([, r]) => [r.x, r.y, r.w, r.h].some(v => !Number.isInteger(v))).map(([key]) => key);
  const data = { description: 'Rectangles of the controls in kit/components/atlas.html as rendered by kit/verify/atlas.mjs, generated by tools/win95-reference/atlas-cells.mjs. Regenerate when the atlas page changes.', image: 'kit/test/baseline/state-atlas.png', viewport: VIEWPORT, fractional, cells };
  await writeFile(out, JSON.stringify(data, null, 1) + '\n');
  if (value('--png')) await writeFile(value('--png'), await page.screenshot({ animations: 'disabled', caret: 'hide' }));
  process.stdout.write(`${Object.keys(cells).length} atlas rectangles written to ${out}${fractional.length ? ` (${fractional.length} not on whole pixels: ${fractional.join(', ')})` : ''}\n`);
} finally { await close(); }
