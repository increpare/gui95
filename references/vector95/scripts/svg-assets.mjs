import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { optimize } from "svgo";

const root = fileURLToPath(new URL("../", import.meta.url));

function compileSvg(source, filename, editable = false) {
  return optimize(source, {
    path: filename,
    // Keep coordinates, IDs, references and layer structure intact. In example
    // drawings the editor metadata is also part of the editable document.
    plugins: [
      "removeDoctype",
      "removeXMLProcInst",
      "removeComments",
      "cleanupAttrs",
      ...(!editable
        ? ["removeMetadata", "removeTitle", "removeDesc", "convertColors"]
        : []),
      {
        name: "validateAsset",
        fn: () => ({
          element: {
            enter(node, parent) {
              if (parent.type !== "root") return;
              if (node.name !== "svg")
                throw new Error(`${filename}: expected an SVG root`);
              const box = (node.attributes.viewBox || "")
                .trim()
                .split(/[\s,]+/)
                .map(Number);
              if (
                box.length !== 4 ||
                !box.every(Number.isFinite) ||
                box[2] <= 0 ||
                box[3] <= 0
              )
                throw new Error(`${filename}: expected a valid viewBox`);
            },
          },
        }),
      },
    ],
  }).data;
}

async function collection(directory, editable = false) {
  const assets = Object.create(null);
  const files = (await fs.readdir(directory))
    .filter((file) => file.endsWith(".svg"))
    .sort();
  for (const file of files) {
    const filename = path.join(directory, file);
    assets[path.basename(file, ".svg")] = compileSvg(
      await fs.readFile(filename, "utf8"),
      filename,
      editable,
    );
  }
  return assets;
}

export async function buildSvgAssets({
  sourceDirectory = path.join(root, "src", "assets"),
  outputDirectory = path.join(root, "src", "generated"),
} = {}) {
  const icons = await collection(path.join(sourceDirectory, "icons"));
  const captions = await collection(path.join(sourceDirectory, "captions"));
  const examples = await collection(
    path.join(sourceDirectory, "examples"),
    true,
  );
  const scrollbars = await collection(path.join(sourceDirectory, "scrollbars"));
  if (!icons.info) throw new Error("The fallback icon info.svg is missing");
  const faviconFile = path.join(sourceDirectory, "favicon.svg");
  const favicon = compileSvg(
    await fs.readFile(faviconFile, "utf8"),
    faviconFile,
  );
  const banner =
    "Generated by scripts/svg-assets.mjs. Edit SVGs under src/assets/ instead.";
  const outputs = {
    "svg-assets.js": `// ${banner}\n${Object.entries({
      icons,
      captions,
      examples,
    })
      .map(
        ([name, assets]) => `export const ${name} = ${JSON.stringify(assets)};`,
      )
      .join("\n")}\n`,
    "svg-assets.css": `/* ${banner} */\n:root {\n${Object.entries(scrollbars)
      .map(
        ([name, svg]) =>
          `  --scrollbar-arrow-${name}: url("data:image/svg+xml,${encodeURIComponent(svg).replace(/'/g, "%27")}");`,
      )
      .join("\n")}\n}\n`,
    "favicon.svg": favicon + "\n",
  };
  // Validate every source before updating any runtime output.
  await fs.mkdir(outputDirectory, { recursive: true });
  for (const [file, content] of Object.entries(outputs)) {
    const destination = path.join(outputDirectory, file);
    let previous;
    try {
      previous = await fs.readFile(destination, "utf8");
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    if (previous !== content) await fs.writeFile(destination, content);
  }
  return {
    count:
      Object.keys(icons).length +
      Object.keys(captions).length +
      Object.keys(examples).length +
      Object.keys(scrollbars).length +
      1,
    outputs,
  };
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href
) {
  const { count } = await buildSvgAssets();
  console.log(`Built ${count} SVG assets.`);
}
