import {spawn} from 'node:child_process';
import {createRequire} from 'node:module';
import {generateIcons} from './gui95-icons.mjs';
const require=createRequire(import.meta.url);
if(process.platform==='darwin'&&process.arch!=='arm64')throw new Error('This delivery standard builds Apple silicon macOS apps; use an arm64 Mac.');
await generateIcons(process.cwd());
const args=[require.resolve('electron-builder/cli.js'),'--dir'];
if(process.platform==='darwin')args.push('--arm64');
const child=spawn(process.execPath,args,{stdio:'inherit',env:{...process.env,CSC_IDENTITY_AUTO_DISCOVERY:'false'}});
child.once('error',error=>{console.error(error);process.exitCode=1;});
child.once('exit',code=>{process.exitCode=code??1;});
